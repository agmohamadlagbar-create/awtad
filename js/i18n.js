let currentLang = typeof localStorage !== 'undefined' ? (localStorage.getItem('ak_steel_lang') || 'en') : 'en';

export function getCurrentLanguage() {
  return currentLang;
}

export function applyLanguage(lang) {
  currentLang = lang;
  if (typeof localStorage !== 'undefined') {
    try { localStorage.setItem('ak_steel_lang', lang); } catch (e) {}
  }

  if (typeof document === 'undefined') return;

  document.documentElement.setAttribute('lang', lang);
  document.documentElement.setAttribute('dir', lang === 'ar' ? 'rtl' : 'ltr');

  // Update text content of translatable elements
  const elements = document.querySelectorAll('[data-i18n]');
  elements.forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (translations[lang] && translations[lang][key] !== undefined) {
      el.innerHTML = translations[lang][key];
    }
  });

  // Update placeholders
  const placeholderElements = document.querySelectorAll('[data-i18n-ph]');
  placeholderElements.forEach((el) => {
    const key = el.getAttribute('data-i18n-ph');
    if (translations[lang] && translations[lang][key]) {
      el.setAttribute('placeholder', translations[lang][key]);
    }
  });

  // Update switcher buttons
  const switcherBtns = document.querySelectorAll('.lang-switcher-btn');
  switcherBtns.forEach((btn) => {
    btn.textContent = lang === 'en' ? 'AR / العربية' : 'EN / English';
  });
}

export function initI18n() {
  const switcherBtns = document.querySelectorAll('.lang-switcher-btn');

  switcherBtns.forEach((btn) => {
    btn.addEventListener('click', () => {
      const nextLang = currentLang === 'en' ? 'ar' : 'en';
      applyLanguage(nextLang);
    });
  });

  applyLanguage(currentLang);
}
